// Trains the statement models on synthetic statements and writes their weights to
// src/classifier/weights.ts. Run with `pnpm --filter @repo/import train`; the same seed
// gives the same weights, so the file changes only when the features or data do.
import { writeFileSync } from 'node:fs'
import {
  columnFeatures,
  columnLabels,
  wordFeatures,
  wordLabels,
} from '../src/classifier/features.ts'
import { type Model, train } from '../src/classifier/model.ts'
import { seeded, syntheticColumns, syntheticDescription } from '../src/classifier/synthetic.ts'

const random = seeded(20261103)

const words = []
for (let row = 0; row < 12000; row += 1) {
  const description = syntheticDescription(random)
  const texts = description.map((item) => item.word)
  for (const [index, item] of description.entries())
    words.push({ features: wordFeatures(texts, index), label: item.label })
}
const columns = []
for (let statement = 0; statement < 4000; statement += 1)
  for (const { sample, label } of syntheticColumns(random))
    columns.push({ features: columnFeatures(sample), label })

const word = train(wordLabels, words, { epochs: 12, rate: 0.2, seed: 1 })
const column = train(columnLabels, columns, { epochs: 20, rate: 0.2, seed: 2 })

const print = (name: string, model: Model) =>
  `export const ${name} = ${JSON.stringify(model)} as const satisfies Model\n`
writeFileSync(
  new URL('../src/classifier/weights.ts', import.meta.url),
  `// Generated by scripts/train-classifier.ts from synthetic statements. Don't edit.\n` +
    `import type { Model } from './model.ts'\n\n` +
    print('wordModel', word) +
    print('columnModel', column),
)
console.log(`Trained on ${String(words.length)} words and ${String(columns.length)} columns.`)
